// lint-authors reads changelogs with the same trailer reach as .githooks/commit-msg
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { join } from "node:path";
import { changelogFails } from "../lint-authors.mjs";

const root = join(import.meta.dirname, "..", "..");

const rejected = [
  ["co-author trailer", "Co-Authored-By: Someone <a@b.c>"],
  ["indented trailer", "  Signed-off-by: Someone <a@b.c>"],
  ["with trailer", "Generated-with: some tool"],
  ["generated hyphen", "notes generated-with a tool"],
  ["generated by", "Generated by a tool"],
  ["anthropic address", "contact noreply@anthropic.com"],
];
const passed = [
  ["plain entry", "- the writer emits a sorted part list"],
  ["word with by", "- stand by for the next release"],
  ["heading", "## 0.1.0"],
];

for (const [name, line] of rejected) {
  test(`changelog rejects ${name}`, () => {
    assert.equal(changelogFails("CHANGELOG.md", `# Changelog\n\n${line}\n`).length, 1);
  });
}
for (const [name, line] of passed) {
  test(`changelog passes ${name}`, () => {
    assert.deepEqual(changelogFails("CHANGELOG.md", `# Changelog\n\n${line}\n`), []);
  });
}

test("importing the module does not run the tracked-file scan", () => {
  const r = spawnSync(process.execPath, ["-e", "import('./tools/lint-authors.mjs').then(() => console.log('ok'))"], { cwd: root, encoding: "utf8" });
  assert.equal(r.status, 0);
  assert.equal(r.stdout.trim(), "ok");
});

test("the cli runs the scan and the tracked tree is clean", () => {
  const r = spawnSync(process.execPath, ["tools/lint-authors.mjs"], { cwd: root, encoding: "utf8" });
  assert.match(r.stdout + r.stderr, /^lint-authors: /m);
  assert.equal(r.status, 0, r.stderr);
});

test("a package.json under legacy/ keeps its shipped author but names no ai tool", async () => {
  const { packageFails, OWNER } = await import("../lint-authors.mjs");
  const legacy = "designs/blocks/legacy/boss-src/package.json";
  assert.deepEqual(packageFails(legacy, JSON.stringify({ name: "boss", author: "" })), []);
  assert.equal(packageFails(legacy, JSON.stringify({ name: "boss", author: "Claude" })).length, 1);
  assert.equal(packageFails(legacy, JSON.stringify({ name: "boss", author: "", contributors: ["Copilot"] })).length, 1);
  // outside a legacy folder the owner string is still required
  assert.equal(packageFails("packages/geom/package.json", JSON.stringify({ name: "g", author: "" })).length, 1);
  assert.equal(packageFails("packages/legacy-ish/package.json", JSON.stringify({ name: "g", author: "" })).length, 1);
  assert.deepEqual(packageFails("packages/geom/package.json", JSON.stringify({ name: "g", author: OWNER })), []);
});

test("pyproject.toml authors must be the owner and name no ai tool", async () => {
  const { pyprojectFails, OWNER } = await import("../lint-authors.mjs");
  const ok = `[project]\nname = "x"\nauthors = [{ name = "Moheeb Zara", email = "hackbuildvideo@gmail.com" }]\n`;
  assert.deepEqual(pyprojectFails("p.toml", ok), []);
  assert.equal(OWNER, "Moheeb Zara <hackbuildvideo@gmail.com>");
  assert.equal(pyprojectFails("p.toml", ok.replace("Moheeb Zara", "Someone")).length, 1);
  assert.equal(pyprojectFails("p.toml", `${ok}maintainers = [{ name = "Claude", email = "noreply@anthropic.com" }]\n`).length, 1);
  assert.equal(pyprojectFails("p.toml", `[project]\nname = "x"\n`).length, 1);
  // the py project of record passes
  const { readFileSync } = await import("node:fs");
  assert.deepEqual(pyprojectFails("py/pyproject.toml", readFileSync(join(root, "py/pyproject.toml"), "utf8")), []);
});

test("one ai name list: the model names and the bare tool names all match", async () => {
  const { AI_IDENTITY } = await import("../ai-names.mjs");
  for (const who of ["Claude", "Sonnet 4.5", "Claude Opus", "GPT-4", "gpt4o", "Codex", "Cursor", "noreply@anthropic.com", "ChatGPT"]) assert.ok(AI_IDENTITY.test(who), who);
  for (const who of ["Moheeb Zara", "hackbuildvideo@gmail.com", "Gemma Opustek"]) assert.ok(!AI_IDENTITY.test(who), who);
  const { AI_NAME } = await import("../lint-authors.mjs");
  const { AI_IDENTITY: commits } = await import("../lint-commits.mjs");
  assert.equal(AI_NAME, AI_IDENTITY);
  assert.equal(commits, AI_IDENTITY);
});

test("a 3mf past the D-166 entry limit is refused before its metadata is read", async () => {
  const { check3mf } = await import("../lint-authors.mjs");
  const JSZip = (await import("node:module")).createRequire(new URL("../../js/package.json", import.meta.url))("jszip");
  const { mkdtempSync, writeFileSync, rmSync } = await import("node:fs");
  const { tmpdir } = await import("node:os");
  const z = new JSZip();
  for (let i = 0; i < 4097; i++) z.file(`x/${i}`, "", { createFolders: false });
  const d = mkdtempSync(join(tmpdir(), "hbf-authors-"));
  try {
    const f = join(d, "many.3mf");
    writeFileSync(f, await z.generateAsync({ type: "nodebuffer" }));
    const fails = [];
    check3mf(f, fails);
    assert.equal(fails.length, 1);
    assert.match(fails[0], /4097 zip entries, legal is at most 4096/);
  } finally {
    rmSync(d, { recursive: true, force: true });
  }
});
