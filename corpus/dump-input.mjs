#!/usr/bin/env node
// Writes tools/corpus/3mf/inputs/flex-pair-two.json, the writer agreement
// input for the M-S exit B print: keys flex-pair on preset two, four slots
// (petg, cpla, tpu95, ctpu), so the TPU preset fallback and its
// PRESET_INFERRED warnings reach tools/py/test/test_agreement.py.
//
// It builds the part with loadDesign and buildPart and lays out the slot
// meshes, filaments and object the way export3mf does (core/src/commands/
// build.ts). Then it builds the written input through the TypeScript writer
// as the agreement test does and stops with exit 1 unless every entry and
// the artifactHash equal those of export3mf on the same build, so the input
// is the export, not a copy of its derivation.
//
//   npx tsc -b && node tools/corpus/3mf/dump-input.mjs           writes the file
//   npx tsc -b && node tools/corpus/3mf/dump-input.mjs --check   exit 1 when the file drifts
//
// Rerun it when the flex-pair geometry, the profile or the writer changes.
// Generated, never hand-edited.

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const OUT = path.join(ROOT, "tools/corpus/3mf/inputs/flex-pair-two.json");
const TARGET = "reference/keys/flex-pair";
const PRESET = "two";
// The agreement test's epoch; the input carries no epoch, but buildHash and
// the cross-check below are taken on this one.
const EPOCH = 1791072000;

for (const p of ["core/dist/resolve-hook.js", "core/dist/commands/build.js", "packages/3mf/dist/index.js"]) {
  if (!existsSync(path.join(ROOT, p))) {
    console.error(`${p} is missing; run npx tsc -b first`);
    process.exit(2);
  }
}
register(pathToFileURL(path.join(ROOT, "core/dist/resolve-hook.js")).href);
const B = await import(pathToFileURL(path.join(ROOT, "core/dist/commands/build.js")).href);
const W = await import(pathToFileURL(path.join(ROOT, "packages/3mf/dist/index.js")).href);

process.env.SOURCE_DATE_EPOCH = String(EPOCH);
const design = await B.loadDesign(TARGET, ROOT);
const built = await B.buildPart(design, B.resolveParams(design.chase, undefined, PRESET));
const { ws, chase } = built.design;
const machine = ws.tables.machines.find((m) => m.id === built.part.machine);
const preset = machine.presets[0];

// export3mf keeps slicerType private; the cross-check below fails when this copy drifts from it.
function slicerType(id) {
  const base = id.toUpperCase().replace(/\d+$/, "");
  const key = Object.keys(ws.materials).filter((t) => base.endsWith(t)).sort((a, b) => b.length - a.length)[0];
  if (key === undefined) throw new Error(`no slicer type for material ${id}`);
  return key;
}

const env = machine.envelope;
const bed = "sheet" in env ? env.sheet : [env[0], env[1]];
const slots = [...chase.materials].sort((a, b) => a.slot - b.slot);
const label = (slot) => slots.find((s) => s.slot === slot)?.label ?? `slot${slot}`;
const shared = (slot) => built.meshed.slots.filter((x) => x.slot === slot).length > 1;
const partName = (p) => (shared(p.slot) ? `${label(p.slot)} ${p.name}` : label(p.slot));
// Body role, conductor width and adjacency as export3mf hands them to the writer (M05-T20 overrides).
const roleOf = new Map(built.part.bodies.map((b) => [b.id, b.role]));
const widthOf = new Map(built.part.features.flatMap((f) => (f.kind === "conductor" ? [[f.id, Number(f.width.toFixed(6))]] : [])));

const input = {
  _source: {
    note: "keys flex-pair on preset two (the M-S exit B print), four slots with two TPU, so both writers take the TPU preset fallback and warn PRESET_INFERRED. Laid out as export3mf does and checked entry by entry against it. Generated by tools/corpus/3mf/dump-input.mjs, never hand-edited.",
    target: TARGET,
    preset: PRESET,
  },
  title: chase.meta.name,
  chase: chase.meta.id,
  buildHash: built.part.buildHash,
  license: chase.meta.license,
  machine: machine.id,
  preset: preset.id,
  filaments: slots.map((s) => ({
    colour: s.preview ?? ws.template.keys["filament_colour"]?.[s.slot - 1] ?? "",
    type: slicerType(s.material),
    material: s.material,
  })),
  objects: [{
    name: path.basename(built.design.dir),
    position: [bed[0] / 2, bed[1] / 2, 0],
    bodies: built.meshed.slots.map((s) => ({
      name: partName(s), slot: s.slot, positions: Array.from(s.mesh.positions), triangles: Array.from(s.mesh.triangles),
      body: s.name, ...(roleOf.get(s.name) === undefined ? {} : { role: roleOf.get(s.name) }),
      ...(widthOf.get(s.name) === undefined ? {} : { widthMm: widthOf.get(s.name) }),
    })),
  }],
  ...(built.part.bodyAdjacency === undefined ? {} : { adjacency: built.part.bodyAdjacency }),
};
const text = JSON.stringify(input);

// The written input through the writer as test_agreement.py builds it, against export3mf.
// The writer gives entries as strings, the zip reader may give bytes; both hash as their UTF-8 bytes.
const sha = (e) => createHash("sha256").update(typeof e === "string" ? Buffer.from(e, "utf8") : e).digest("hex");
const inp = JSON.parse(text);
const row = machine.presets.find((p) => p.id === inp.preset);
const fromInput = W.build(W.configOf({
  title: inp.title, chase: inp.chase, buildHash: inp.buildHash, sourceDateEpoch: EPOCH, license: inp.license,
  slicer: row.slicer, nozzleMm: row.nozzle, template: W.DEFAULT_TEMPLATE, materials: W.DEFAULT_MATERIALS,
  filaments: inp.filaments,
  ...(inp.adjacency === undefined ? {} : { adjacency: inp.adjacency }),
  objects: inp.objects.map((o) => ({ name: o.name, position: o.position,
    bodies: o.bodies.map((b) => ({ name: b.name, slot: b.slot, mesh: { positions: b.positions, triangles: b.triangles },
      ...(b.body === undefined ? {} : { body: b.body }), ...(b.role === undefined ? {} : { role: b.role }),
      ...(b.widthMm === undefined ? {} : { widthMm: b.widthMm }) })) })),
}));
if (!fromInput.ok) {
  console.error(`the written input fails export completeness: ${JSON.stringify(fromInput.completeness)}`);
  process.exit(1);
}
const exported = await B.export3mf(built);
const exportedEntries = await W.readEntries(exported.bytes);
const differ = [...new Set([...Object.keys(fromInput.entries), ...Object.keys(exportedEntries)])].sort()
  .filter((k) => fromInput.entries[k] === undefined || exportedEntries[k] === undefined || sha(fromInput.entries[k]) !== sha(exportedEntries[k]));
const codes = (list) => list.map((w) => w.code).join(",");
if (differ.length > 0 || fromInput.artifactHash !== exported.artifactHash || codes(fromInput.warnings) !== codes(exported.warnings)) {
  console.error(`the input does not rebuild the export: entries differ ${JSON.stringify(differ)}, artifactHash ${fromInput.artifactHash} vs ${exported.artifactHash}, warnings ${codes(fromInput.warnings)} vs ${codes(exported.warnings)}`);
  process.exit(1);
}

const summary = `${path.relative(ROOT, OUT)}: ${inp.filaments.map((f) => f.material).join(", ")}; artifactHash ${exported.artifactHash}; warnings ${codes(exported.warnings) || "none"}`;
if (process.argv.includes("--check")) {
  const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (have !== text) {
    // Top-level fields only: a moved mesh shows as objects, a moved hash as buildHash.
    let old = {};
    try { old = JSON.parse(have); } catch { /* absent or unreadable: every field reads as moved */ }
    const moved = Object.keys({ ...old, ...inp }).filter((k) => JSON.stringify(old[k]) !== JSON.stringify(inp[k]));
    const hash = (h) => (typeof h === "string" ? h.slice(0, 8) : "none");
    console.error(`${path.relative(ROOT, OUT)} drifted from the flex-pair build: fields moved ${moved.join(", ")}; buildHash ${hash(old.buildHash)} committed, ${hash(inp.buildHash)} built. regenerate with: npx tsc -b && node tools/corpus/3mf/dump-input.mjs, then commit the file`);
    process.exit(1);
  }
  console.log(`unchanged ${summary}`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${summary}`);
}
