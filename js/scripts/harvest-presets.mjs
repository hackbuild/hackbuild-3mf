// Harvests filament preset rows from slicer saves into
// packages/3mf/data/filament_presets.json (D-159, M00-T07 step 2).
//
// A row is one column of a save's project_settings.config, keyed by the
// filament_settings_id that column names, over the 127 template keys of
// packages/3mf/data/filament_template.json. Only slicer saves are read: a
// writer-made file would feed the writer its own guesses. Two saves naming
// one preset must agree on every key except the slot identity keys, or the
// harvest stops.
//
//   npm run check:presets --prefix js          write the file
//   npm run check:presets --prefix js --check  fail on drift
//
// Saves are opened through the package reader (readEntries, ARCHITECTURE.md
// 11.1 limits) from the compiled dist, so run `npx tsc -b` first.

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PKG = path.resolve(HERE, "..");
const REPO = path.resolve(PKG, "..");
// In hackbuild-fab, @hackbuild/spec loads as TypeScript through core's resolve
// hook, as hbf does; the hackbuild-3mf split carries the contracts and has no core.
const HOOK = path.join(REPO, "core/dist/resolve-hook.js");
if (existsSync(HOOK)) register(pathToFileURL(HOOK).href);
const { readEntries } = await import(pathToFileURL(path.join(PKG, "dist/index.js")).href);
const OUT = path.join(PKG, "data", "filament_presets.json");

/** Slicer saves, each with where it came from. Order sets which save a row cites. */
const SAVES = [
  {
    file: "corpus/gold/hackbuild-coin-nfc.3mf",
    note: "gold round trip, Flash Studio save of 2026-08-19 (zip entry dates)",
  },
  {
    file: "corpus/owner/tang-small/facewithbuttons.3mf",
    note: "Flash Studio save carrying Generic PLA @FF C5P (M00-T07 step 2)",
  },
];

/** Keys that follow the loaded slot, never the preset. */
const SLOT_IDENTITY = new Set(["filament_colour", "filament_multi_colour", "filament_self_index"]);

const template = JSON.parse(readFileSync(path.join(PKG, "data", "filament_template.json"), "utf8"));
const keys = Object.keys(template.keys).sort();

const rows = {};
const sources = [];
for (const save of SAVES) {
  const abs = path.isAbsolute(save.file) ? save.file : path.join(REPO, save.file);
  if (!existsSync(abs)) throw new Error(`slicer save missing: ${abs}`);
  const bytes = readFileSync(abs);
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const entry = (await readEntries(bytes))["Metadata/project_settings.config"];
  if (typeof entry !== "string") throw new Error(`${save.file} has no Metadata/project_settings.config`);
  const ps = JSON.parse(entry);
  const app = `${ps["from"] === "project" ? "" : "not a project save, "}version ${ps["version"]}`;
  const n = ps["filament_settings_id"].length;
  const missing = keys.filter((k) => !Array.isArray(ps[k]) || ps[k].length !== n);
  if (missing.length > 0) throw new Error(`${save.file} lacks ${missing.length} template keys: ${missing.slice(0, 5).join(", ")}`);
  sources.push({ file: save.file, sha256, note: save.note, filaments: n, version: app });
  for (let slot = 0; slot < n; slot += 1) {
    const id = ps["filament_settings_id"][slot];
    const values = Object.fromEntries(keys.map((k) => [k, ps[k][slot]]));
    const prior = rows[id];
    if (prior !== undefined) {
      const differ = keys.filter((k) => !SLOT_IDENTITY.has(k) && prior.values[k] !== values[k]);
      if (differ.length > 0) throw new Error(`${id}: ${save.file} slot ${slot + 1} disagrees with ${prior.source} on ${differ.join(", ")}`);
      continue;
    }
    rows[id] = { source: save.file, slot: slot + 1, tier: "vendor", values };
  }
}

const sorted = Object.fromEntries(Object.keys(rows).sort().map((k) => [k, rows[k]]));
const text = `${JSON.stringify({
  note: "generated by packages/3mf/scripts/harvest-presets.mjs; never hand-edit. One row per slicer preset, 127 template keys, values as the slicer saved them.",
  sources,
  rows: sorted,
}, null, 1)}\n`;

if (process.argv.includes("--check")) {
  const now = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (now !== text) {
    console.error(`${path.relative(REPO, OUT)} drifted from the saves; run npm run check:presets --prefix js`);
    process.exit(1);
  }
  console.log(`${path.relative(REPO, OUT)} matches ${sources.length} saves, ${Object.keys(sorted).length} rows`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(REPO, OUT)}: ${Object.keys(sorted).length} rows from ${sources.length} saves`);
}
